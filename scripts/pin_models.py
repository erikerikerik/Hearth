#!/usr/bin/env python3
"""Developer tool: write models/manifest.json with every model pinned to an exact revision.

For each model named in config/models.json (every LLM profile, plus STT and TTS) this asks the
Hugging Face API for one commit and records every file the app needs with its size and hash:
  * large (LFS) files carry the sha256 published for that commit;
  * small git files carry their git blob sha1, which the downloader recomputes.
The installer's downloader (tools/model_manager.py) refuses anything that does not match.

This script runs on a developer machine only. It is NOT copied into Hearth.app and the companion
never runs it.

  python3 scripts/pin_models.py                       pin each repo's current "main" commit
  python3 scripts/pin_models.py --revision-from-cache pin the exact commits already in your local
                                                      Hugging Face cache (what you actually tested)
  python3 scripts/pin_models.py --check               fail if the manifest is not fully pinned
"""

import argparse
import fnmatch
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HUB = "https://huggingface.co"
HEX40 = re.compile(r"^[0-9a-f]{40}$")
# Documentation, samples and duplicate PyTorch voice files are never needed at run time.
EXCLUDE = [".gitattributes", "*.md", "samples/*", "voices/*.pt", "*.png", "*.jpg", "*.gif"]


def wanted(path: str) -> bool:
    return not any(fnmatch.fnmatch(path, pattern) for pattern in EXCLUDE)


def api(url: str) -> dict:
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "hearth-pin-models"}), timeout=60) as r:
        return json.load(r)


def cached_revision(repo: str) -> str:
    home = Path(os.environ.get("HF_HOME") or Path.home() / ".cache" / "huggingface")
    ref = home / "hub" / ("models--" + repo.replace("/", "--")) / "refs" / "main"
    value = ref.read_text().strip() if ref.is_file() else ""
    if not HEX40.match(value):
        raise SystemExit("No cached revision for %s at %s. Run without --revision-from-cache." % (repo, ref))
    return value


def snapshot_entry(entry_id: str, role: str, repo: str, min_ram_gb: float, revision: str, profile=None) -> dict:
    quoted = urllib.parse.quote(repo, safe="/")
    info = api("%s/api/models/%s" % (HUB, quoted))
    rev = revision or info["sha"]
    detail = api("%s/api/models/%s/revision/%s?blobs=true" % (HUB, quoted, rev))
    files = []
    for sibling in sorted(detail["siblings"], key=lambda s: s["rfilename"]):
        path = sibling["rfilename"]
        if not wanted(path):
            continue
        record = {"path": path, "size": int(sibling["size"])}
        lfs = sibling.get("lfs") or {}
        if lfs.get("sha256"):
            record["sha256"] = lfs["sha256"]
        else:
            record["git_sha1"] = sibling["blobId"]
        files.append(record)
    entry = {
        "id": entry_id,
        "role": role,
        "repo": repo,
        "revision": detail.get("sha", rev),
        "min_ram_gb": min_ram_gb,
        "license": (info.get("cardData") or {}).get("license", "see model card"),
        "files": files,
    }
    if profile:
        entry["profile"] = profile
    return entry


def build(from_cache: bool) -> dict:
    config = json.loads((ROOT / "config" / "models.json").read_text())
    entries = []
    for name, profile in config["profiles"].items():
        repo = profile["mlx"]
        entries.append(snapshot_entry("llm-" + name, "llm", repo, profile["min_ram_gb"],
                                      cached_revision(repo) if from_cache else "", profile=name))
    for role in ("stt", "tts"):
        repo = config[role]["mlx"]
        entries.append(snapshot_entry(role, role, repo, 8, cached_revision(repo) if from_cache else ""))
    return {
        "schema": 2,
        "_note": "Generated by scripts/pin_models.py. Do not edit by hand. Every file is fetched from "
                 "<hub>/<repo>/resolve/<revision>/<path> and must match its size and hash.",
        "hub": HUB,
        "default_profile": config["default_profile"],
        "snapshots": entries,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--revision-from-cache", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--out", default=str(ROOT / "models" / "manifest.json"))
    args = parser.parse_args(argv)
    if args.check:
        sys.path.insert(0, str(ROOT))
        from tools import model_manager
        snapshots = model_manager.load_manifest(Path(args.out))["snapshots"]
        unpinned = [s["id"] for s in snapshots if not model_manager.is_pinned(s)]
        if unpinned:
            raise SystemExit("Unpinned: " + ", ".join(unpinned))
        print("All %d snapshots are pinned." % len(snapshots))
        return
    manifest = build(args.revision_from_cache)
    Path(args.out).write_text(json.dumps(manifest, indent=1) + "\n")
    for entry in manifest["snapshots"]:
        total = sum(f["size"] for f in entry["files"])
        print("%-12s %-48s %s  %5.2f GB  %d files" % (entry["id"], entry["repo"], entry["revision"][:12], total / 1e9, len(entry["files"])))


if __name__ == "__main__":
    main()
